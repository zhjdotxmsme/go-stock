// GetRolePrompt loads the prompt for a role key from DB, falling back to the hardcoded constant.
func GetRolePrompt(roleKey string, fallback string) string {
	if p := data.GetPromptByRoleKey(roleKey); p != "" {
		return p
	}
	return fallback
}

